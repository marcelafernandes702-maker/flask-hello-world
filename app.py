# stumbleBrack backend An **independent** backend for a custom application managing player and bot profiles. It does not connect to or modify the official Stumble Guys client or server. ## Requirements - Node.js 20+ ## Running ```bash cd stumbleBrack-backend SETNICK_SECRET="a-strong-key" npm start ``` The API starts at `http://localhost:3000`. Data is stored in `data/profiles.json` and is saved atomically. ## API ### Create a player or bot ```bash curl -X POST http://localhost:3000/profiles \ -H 'content-type: application/json' \ -d '{"name":"Player 1","type":"player"}' ``` The `type` field only accepts `player` or `bot`. The name is mandatory and has a limit of **67 characters**. ### List profiles ```bash curl http://localhost:3000/profiles curl 'http://localhost:3000/profiles?type=bot' ``` ### Change nickname using the secret command Replace `PROFILE_ID` with the `id` returned when the profile was created: ```bash curl -X POST http://localhost:3000/profiles/PROFILE_ID/command \ -H 'content-type: application/json' \ -H 'x-setnick-secret: a-strong-key' \ -d '{"command":"<setnick=.gg/stumblelend>"}' ``` The command must strictly follow the format `<setnick=color>`. The secret key must only be sent via the `x-setnick-secret` header; do not include the secret in your code or frontend. ### Health ```bash curl http://localhost:3000/health ``` ## Tests ```bash npm test ``` ## Production Notes For production, use HTTPS, a long key stored in an environment variable, rate limiting, logs that exclude sensitive information, and a proper database (PostgreSQL/SQLite) if running multiple instances. JSON-based storage is suitable only for prototypes or single-server setups. An independent backend for player and bot profiles, featuring a secure `setnick` command.



















    




